import 'package:xml/xml.dart';
import '../../core/models/drum_kit.dart';
import '../../core/models/note.dart';
import '../../core/models/part.dart';
import '../../core/models/part_playback.dart';

/// A pitched instrument or percussion pieces sharing one kit and mix.
/// Other instrument combinations and non-GM banks remain in retained XML.
class MusicXmlInstruments {
  static PartPlayback read(XmlElement? declaration) {
    final midi = declaration?.findElements('midi-instrument').toList() ?? [];
    final percussion =
        midi.isNotEmpty &&
        midi.every(
          (e) =>
              e.getElement('midi-unpitched') != null &&
              (e.getElement('midi-bank')?.innerText.trim() ?? '1') == '1' &&
              ['midi-program', 'volume', 'pan'].every(
                (name) =>
                    e.getElement(name)?.innerText ==
                    midi.first.getElement(name)?.innerText,
              ),
        );
    if (!percussion && (midi.length != 1 || !_supported(midi.single))) {
      return const PartPlayback();
    }
    final e = midi.first;
    double number(String name, double fallback) =>
        double.tryParse(e.getElement(name)?.innerText.trim() ?? '') ?? fallback;
    return PartPlayback.fromJson({
      'program': (number('midi-program', 1) - 1).toInt(),
      'volume': number('volume', 100),
      'pan': number('pan', 0),
    });
  }

  /// On a single-line percussion staff, all of its declared pieces sit on
  /// the line. Known orchestral pieces retain their input shortcuts/heads.
  static List<DrumPiece>? readDrumMap(XmlElement? declaration) {
    final midis =
        declaration
            ?.findElements('midi-instrument')
            .where(
              (e) =>
                  int.tryParse(
                    e.getElement('midi-unpitched')?.innerText ?? '',
                  ) !=
                  null,
            )
            .toList() ??
        [];
    if (midis.isEmpty) return null;
    int key(XmlElement e) =>
        int.parse(e.getElement('midi-unpitched')!.innerText) - 1;
    midis.sort((a, b) {
      final preferred = (key(a) == 38 ? 0 : 1).compareTo(key(b) == 38 ? 0 : 1);
      return preferred != 0 ? preferred : key(a).compareTo(key(b));
    });
    return [
      for (final e in midis)
        () {
          final k = key(e);
          final known = [
            ...orchestralSnare,
            ...orchestralBassDrum,
            ...orchestralCymbals,
          ].where((d) => d.key == k).firstOrNull;
          final name = declaration!
              .findElements('score-instrument')
              .where((i) => i.getAttribute('id') == e.getAttribute('id'))
              .firstOrNull
              ?.getElement('instrument-name')
              ?.innerText;
          return DrumPiece(
            k,
            name ?? known?.name ?? 'Drum $k',
            'B',
            4,
            notehead: known?.notehead,
            shortcut: known?.shortcut,
          );
        }(),
    ];
  }

  /// Declarations generated by this app are completely represented. Unknown
  /// instrument metadata still requires retained-source export.
  static bool canRebuildDeclaration(XmlElement declaration) {
    final id = '${declaration.getAttribute('id')}-NV-I1';
    final instruments = declaration.findElements('score-instrument').toList();
    final midis = declaration.findElements('midi-instrument').toList();
    if (instruments.length != 1 || midis.length != 1) return false;
    final instrument = instruments.single, midi = midis.single;
    if (instrument.getAttribute('id') != id ||
        midi.getAttribute('id') != id ||
        instrument.attributes.length != 1 ||
        midi.attributes.length != 1 ||
        !_supported(midi)) {
      return false;
    }
    if (instrument.childElements.length != 1 ||
        instrument.getElement('instrument-name')?.innerText !=
            gmSounds[read(declaration).program]) {
      return false;
    }
    return [...instrument.childElements, ...midi.childElements].every(
      (e) =>
          {
            'instrument-name',
            'midi-program',
            'volume',
            'pan',
          }.contains(e.name.local) &&
          e.attributes.isEmpty &&
          e.childElements.isEmpty,
    );
  }

  static bool _supported(XmlElement e) =>
      e.getElement('midi-unpitched') == null &&
      (e.getElement('midi-bank')?.innerText.trim() ?? '1') == '1';

  /// Change only the edited fields, preserving IDs, device declarations and
  /// any other instrument metadata in its original order.
  static void patch(
    XmlElement declaration,
    PartPlayback before,
    PartPlayback after,
  ) {
    if (before.program == after.program &&
        before.volume == after.volume &&
        before.pan == after.pan) {
      return;
    }
    final midis = declaration.findElements('midi-instrument').toList();
    final instruments = declaration.findElements('score-instrument').toList();
    final percussion =
        midis.isNotEmpty &&
        midis.every(
          (e) =>
              e.getElement('midi-unpitched') != null &&
              (e.getElement('midi-bank')?.innerText.trim() ?? '1') == '1',
        );
    if (percussion) {
      for (final midi in midis) {
        if (before.program != after.program) {
          _setMidi(midi, 'midi-program', '${after.program + 1}');
        }
        if (before.volume != after.volume) {
          _setMidi(midi, 'volume', '${after.volume}');
        }
        if (before.pan != after.pan) _setMidi(midi, 'pan', '${after.pan}');
      }
      return;
    }
    if (midis.length > 1 ||
        instruments.length > 1 ||
        (midis.isNotEmpty && !_supported(midis.single))) {
      throw const FormatException(
        'Sound export for multiple pitched instruments or non-GM banks is not supported yet. Saving the project keeps mixer settings.',
      );
    }
    final partId = declaration.getAttribute('id') ?? 'P1';
    final id =
        midis.firstOrNull?.getAttribute('id') ??
        instruments.firstOrNull?.getAttribute('id') ??
        '$partId-NV-I1';
    if (instruments.isEmpty) {
      final instrument = XmlElement(
        XmlName('score-instrument'),
        [XmlAttribute(XmlName('id'), id)],
        [
          XmlElement(XmlName('instrument-name'), [], [
            XmlText(gmSounds[after.program]),
          ]),
        ],
      );
      final next = declaration.childElements
          .where(
            (e) => {'midi-device', 'midi-instrument'}.contains(e.name.local),
          )
          .firstOrNull;
      if (next == null) {
        declaration.children.add(instrument);
      } else {
        declaration.children.insert(
          declaration.children.indexOf(next),
          instrument,
        );
      }
    }
    final midi =
        midis.firstOrNull ??
        XmlElement(XmlName('midi-instrument'), [
          XmlAttribute(XmlName('id'), id),
        ]);
    if (midis.isEmpty) declaration.children.add(midi);

    if (before.program != after.program || midis.isEmpty) {
      _setMidi(midi, 'midi-program', '${after.program + 1}');
    }
    if (before.volume != after.volume || midis.isEmpty) {
      _setMidi(midi, 'volume', '${after.volume}');
    }
    if (before.pan != after.pan || midis.isEmpty) {
      _setMidi(midi, 'pan', '${after.pan}');
    }
  }

  static void _setMidi(XmlElement midi, String name, String value) {
    const order = [
      'midi-channel',
      'midi-name',
      'midi-bank',
      'midi-program',
      'midi-unpitched',
      'volume',
      'pan',
      'elevation',
    ];
    var e = midi.getElement(name);
    if (e == null) {
      e = XmlElement(XmlName(name));
      final next = midi.childElements
          .where((n) => order.indexOf(n.name.local) > order.indexOf(name))
          .firstOrNull;
      if (next == null) {
        midi.children.add(e);
      } else {
        midi.children.insert(midi.children.indexOf(next), e);
      }
    }
    e.children
      ..clear()
      ..add(XmlText(value));
  }

  /// A drum kit piece's instrument id, as MuseScore Studio writes it.
  static String drumId(String partId, int key) => '$partId-I${key + 1}';

  /// A drum part's kit: one instrument per piece, on MIDI channel 10, the
  /// standard kit and any other pieces its notes play.
  static void writeDrums(XmlBuilder b, Part part) {
    final keys = {
      for (final d in part.drums) d.key,
      for (final m in part.measures)
        for (final s in m.symbols)
          if (s is Note && s.drum != null) s.drum!,
    }.toList()..sort();
    for (final key in keys) {
      b.element(
        'score-instrument',
        attributes: {'id': drumId(part.id, key)},
        nest: () => b.element(
          'instrument-name',
          nest:
              part.drums.where((d) => d.key == key).firstOrNull?.name ??
              drumPiece(key)?.name ??
              'Drum $key',
        ),
      );
    }
    for (final key in keys) {
      b.element(
        'midi-instrument',
        attributes: {'id': drumId(part.id, key)},
        nest: () {
          b.element('midi-channel', nest: '10');
          b.element('midi-program', nest: '${part.playback.program + 1}');
          b.element('midi-unpitched', nest: '${key + 1}');
          b.element('volume', nest: '${part.playback.volume}');
          b.element('pan', nest: '${part.playback.pan}');
        },
      );
    }
  }

  static void write(XmlBuilder b, String partId, PartPlayback value) {
    final id = '$partId-NV-I1';
    b.element(
      'score-instrument',
      attributes: {'id': id},
      nest: () {
        b.element('instrument-name', nest: gmSounds[value.program]);
      },
    );
    b.element(
      'midi-instrument',
      attributes: {'id': id},
      nest: () {
        b.element('midi-program', nest: '${value.program + 1}');
        b.element('volume', nest: '${value.volume}');
        b.element('pan', nest: '${value.pan}');
      },
    );
  }
}
